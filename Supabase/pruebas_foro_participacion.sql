-- Verificación real con anon/authenticated; no deja contenido ni cuentas de prueba.
BEGIN;
DO $$
DECLARE autor uuid:=gen_random_uuid(); otro uuid:=gen_random_uuid(); personal uuid:=gen_random_uuid();
 sa uuid:=gen_random_uuid(); so uuid:=gen_random_uuid(); sp uuid:=gen_random_uuid(); cuenta uuid;
 tema uuid:=gen_random_uuid(); comentario uuid:=gen_random_uuid(); segundo uuid:=gen_random_uuid();
 r jsonb; previo jsonb; datos jsonb; bloqueo boolean; reporte uuid;
 registro jsonb:='{"nombres":"Integración foro","primerApellido":"Temporal","fechaNacimiento":"2000-01-01","telefono":"3110000000","aceptaAviso":true,"domicilio":{"calle":"Prueba","numeroExterior":"sin número","coloniaLocalidad":"Prueba","codigoPostal":"63000","municipio":"Tepic","estadoProvincia":"Nayarit"}}';
BEGIN
 FOREACH cuenta IN ARRAY ARRAY[autor,otro,personal] LOOP
  INSERT INTO auth.users(id,email,email_confirmed_at,raw_user_meta_data) VALUES(cuenta,cuenta::text||'@example.invalid',now(),jsonb_build_object('registro',registro));
 END LOOP;
 INSERT INTO auth.sessions(id,user_id,created_at) VALUES(sa,autor,now()),(so,otro,now()),(sp,personal,now());
 INSERT INTO public."rolUsuario"("usuarioId","rolCodigo","asignadoPor","motivoAsignacion") VALUES(personal,'responsable_actividades',personal,'Prueba reversible');
 INSERT INTO public."permisoCuenta"("usuarioId",capacidad,"asignadoPor",motivo) VALUES(personal,'moderar_foro',personal,'Prueba reversible');
 PERFORM set_config('request.jwt.claims','{}',true); SET LOCAL ROLE anon; bloqueo:=false;
 BEGIN PERFORM public.foro_participacion('crear','{}'); EXCEPTION WHEN insufficient_privilege THEN bloqueo:=true; END;
 IF NOT bloqueo THEN RAISE EXCEPTION 'Anon publica'; END IF;
 r:=public.foro_lectura('temas');
 IF EXISTS(SELECT 1 FROM jsonb_array_elements(r->'temas') t WHERE t ? 'creadoPor' OR t ? 'moderadoPor') THEN RAISE EXCEPTION 'Exposición de identificadores privados'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',autor,'role','authenticated','session_id',sa)::text,true); SET LOCAL ROLE authenticated;
 r:=public.foro_participacion('crear',jsonb_build_object('tipo','tema','id',tema,'titulo','Tema integración','texto','Conversación reversible'));
 IF r->>'estado'<>'pendiente' THEN RAISE EXCEPTION 'Tema sin revisión'; END IF;
 previo:=r; bloqueo:=false;
 BEGIN PERFORM public.foro_participacion('revisar',jsonb_build_object('tipo','tema','id',tema,'version',r->>'version','medida','publicar','motivo','Yo mismo'));
 EXCEPTION WHEN insufficient_privilege THEN bloqueo:=true; END;
 IF NOT bloqueo THEN RAISE EXCEPTION 'Autor se autoriza'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',personal,'role','authenticated','session_id',sp)::text,true); SET LOCAL ROLE authenticated;
 r:=public.foro_participacion('pendientes');
 IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(r->'contenidos') t WHERE t->>'id'=tema::text) THEN RAISE EXCEPTION 'Tema no llegó a revisión'; END IF;
 r:=public.foro_participacion('revisar',jsonb_build_object('tipo','tema','id',tema,'version',previo->>'version','medida','publicar','motivo','Cumple las normas'));
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',autor,'role','authenticated','session_id',sa)::text,true); SET LOCAL ROLE authenticated;
 datos:=jsonb_build_object('tipo','comentario','id',comentario,'temaId',tema,'texto','Mi primera respuesta');
 r:=public.foro_participacion('crear',datos); previo:=r;
 IF r->>'estado'<>'pendiente' THEN RAISE EXCEPTION 'Primera respuesta pública sin aprobación'; END IF;
 r:=public.foro_participacion('crear',datos);
 IF r->>'id'<>comentario::text THEN RAISE EXCEPTION 'Reintento no idempotente'; END IF;
 r:=public.foro_lectura('respuestas',jsonb_build_object('temaId',tema));
 IF r->>'total'<>'1' OR r->'respuestas'->0->>'propia'<>'true' THEN RAISE EXCEPTION 'Autor no ve respuesta pendiente'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',otro,'role','authenticated','session_id',so)::text,true); SET LOCAL ROLE authenticated;
 r:=public.foro_lectura('respuestas',jsonb_build_object('temaId',tema));
 IF r->>'total'<>'0' THEN RAISE EXCEPTION 'Pendiente visible para otra cuenta'; END IF;
 bloqueo:=false;
 BEGIN PERFORM public.foro_participacion('editar',jsonb_build_object('tipo','comentario','id',comentario,'texto','Ajeno','version',previo->>'version'));
 EXCEPTION WHEN insufficient_privilege THEN bloqueo:=true; END;
 IF NOT bloqueo THEN RAISE EXCEPTION 'Edición ajena'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims','{}',true); SET LOCAL ROLE anon;
 r:=public.foro_lectura('respuestas',jsonb_build_object('temaId',tema));
 IF r->>'total'<>'0' THEN RAISE EXCEPTION 'Pendiente visible públicamente'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',personal,'role','authenticated','session_id',sp)::text,true); SET LOCAL ROLE authenticated;
 r:=public.foro_participacion('revisar',jsonb_build_object('tipo','comentario','id',comentario,'version',previo->>'version','medida','publicar','motivo','Primera respuesta revisada')); previo:=r;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims','{}',true); SET LOCAL ROLE anon;
 r:=public.foro_lectura('respuestas',jsonb_build_object('temaId',tema));
 IF r->>'total'<>'1' OR r->'respuestas'->0 ? 'creadoPor' OR r->'respuestas'->0->>'propia'<>'false' THEN RAISE EXCEPTION 'Lectura pública incorrecta'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',autor,'role','authenticated','session_id',sa)::text,true); SET LOCAL ROLE authenticated;
 r:=public.foro_participacion('crear',jsonb_build_object('tipo','comentario','id',segundo,'temaId',tema,'texto','Segunda después de aprobación'));
 IF r->>'estado'<>'publicado' THEN RAISE EXCEPTION 'No reconoce aprobación previa'; END IF;
 r:=public.foro_participacion('editar',jsonb_build_object('tipo','comentario','id',comentario,'texto','Respuesta editada','version',previo->>'version'));
 IF r->>'estado'<>'pendiente' THEN RAISE EXCEPTION 'La edición no vuelve al filtro'; END IF;
 bloqueo:=false;
 BEGIN PERFORM public.foro_participacion('editar',jsonb_build_object('tipo','comentario','id',comentario,'texto','Versión vieja','version',previo->>'version'));
 EXCEPTION WHEN serialization_failure THEN bloqueo:=true; END;
 IF NOT bloqueo THEN RAISE EXCEPTION 'Acepta edición obsoleta'; END IF;
 r:=public.foro_participacion('retirar',jsonb_build_object('tipo','comentario','id',comentario,'version',r->>'version'));
 IF r->>'estado'<>'retirado' THEN RAISE EXCEPTION 'Retiro propio falló'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',otro,'role','authenticated','session_id',so)::text,true); SET LOCAL ROLE authenticated;
 r:=public.foro_moderacion('reportar',jsonb_build_object('tipoContenido','comentario','contenidoId',segundo,'motivo','Prueba de reporte persistente')); reporte:=(r->>'reporteId')::uuid;
 r:=public.foro_lectura('respuestas',jsonb_build_object('temaId',tema));
 IF r->'respuestas'->0->>'reportada'<>'true' THEN RAISE EXCEPTION 'No persiste el reporte propio'; END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',personal,'role','authenticated','session_id',sp)::text,true); SET LOCAL ROLE authenticated;
 r:=public.foro_moderacion('obtener',jsonb_build_object('id',reporte));
 r:=public.foro_moderacion('resolver',jsonb_build_object('id',reporte,'actualizadoEn',r->>'actualizadoEn','versionContenido',r->'contenido'->>'version','medida','ocultar','motivo','Se oculta la prueba'));
 RESET ROLE;
 PERFORM set_config('request.jwt.claims','{}',true); SET LOCAL ROLE anon;
 r:=public.foro_lectura('respuestas',jsonb_build_object('temaId',tema));
 IF r->>'total'<>'0' THEN RAISE EXCEPTION 'Retirados u ocultos siguen públicos'; END IF;
 RESET ROLE;
 IF (SELECT count(*) FROM privado."historialRevisionForo" WHERE "comentarioId"=comentario)<>4 THEN RAISE EXCEPTION 'Historial incompleto'; END IF;
 IF (SELECT count(*) FROM public."comentarioForo" WHERE id=comentario)<>1 THEN RAISE EXCEPTION 'Reintento duplicó respuesta'; END IF;
 UPDATE auth.sessions SET not_after=now()-interval '1 minute' WHERE id=sa;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',autor,'role','authenticated','session_id',sa)::text,true); SET LOCAL ROLE authenticated; bloqueo:=false;
 BEGIN PERFORM public.foro_participacion('crear',datos); EXCEPTION WHEN insufficient_privilege THEN bloqueo:=true; END;
 IF NOT bloqueo THEN RAISE EXCEPTION 'Sesión expirada participa'; END IF;
 RESET ROLE;
END; $$;
ROLLBACK;
